import { act, create, type ReactTestRenderer } from 'react-test-renderer';
import { expect, it, vi } from 'vitest';
import { documentProperties, ownerUnlockDocument, type DocumentPropertiesInfo } from './bridge';
import DocumentProperties from './DocumentProperties';
import type { DocumentInfo } from './model';
vi.mock('./bridge', () => ({ documentProperties: vi.fn(), ownerUnlockDocument: vi.fn() }));
const document: DocumentInfo = { id: 1, name: 'test.pdf', path: 'test.pdf', pages: [{ width: 612, height: 792 }], revision: 4, dirty: true, can_undo: true, can_redo: false };
const info: DocumentPropertiesInfo = { version: null, source_size_bytes: 1234, page_count: 1, metadata: [{ name: 'title', value: '<script>PDF text</script>', truncated: true }], page_dimensions: [{ width_points: 612, height_points: 792, count: 1 }], page_dimensions_truncated: true, security: { encrypted: null, handler_revision: null, print_high_quality: null, print_low_quality_only: null, modify_contents: null, assemble_document: null, fill_existing_forms: null }, reported_signature_count: 2, signature_validation: 'not_performed' };
it('shows metadata as text, unknown permissions and signature-validation limits', async () => {
  vi.mocked(documentProperties).mockResolvedValue(info);
  let ui!: ReactTestRenderer;
  await act(async () => { ui = create(<DocumentProperties document={document} close={vi.fn()} />); });
  expect(documentProperties).toHaveBeenCalledWith(1, 4);
  expect(ui.root.findAllByType('script')).toHaveLength(0);
  const text = JSON.stringify(ui.toJSON());
  for (const value of ['<script>PDF text</script>', 'Unknown', '(truncated)', 'first 128', 'Signature validity has not been checked', 'original file']) expect(text).toContain(value);
  act(() => ui.unmount());
});
it('ignores a previous document response and distinguishes failure from missing metadata', async () => {
  let resolveOld!: (info: DocumentPropertiesInfo) => void;
  vi.mocked(documentProperties).mockReturnValueOnce(new Promise(resolve => { resolveOld = resolve; })).mockResolvedValueOnce({ ...info, metadata: [] });
  let ui!: ReactTestRenderer;
  await act(async () => { ui = create(<DocumentProperties document={document} close={vi.fn()} />); });
  await act(async () => { ui.update(<DocumentProperties document={{ ...document, id: 2 }} close={vi.fn()} />); });
  await act(async () => { resolveOld(info); });
  expect(JSON.stringify(ui.toJSON())).toContain('No description metadata was found');
  expect(JSON.stringify(ui.toJSON())).not.toContain('<script>PDF text</script>');
  vi.mocked(documentProperties).mockRejectedValueOnce(new Error('Document is closed'));
  await act(async () => { ui.update(<DocumentProperties document={{ ...document, id: 3 }} close={vi.fn()} />); });
  expect(ui.root.findByProps({ role: 'alert' }).children).toEqual(['Error: Document is closed']);
  act(() => ui.unmount());
});
const locked: DocumentPropertiesInfo = { ...info, security: { ...info.security, encrypted: true, handler_revision: 3, modify_contents: false } };
const unlocked: DocumentPropertiesInfo = { ...info, security: { ...info.security, encrypted: false, handler_revision: null, modify_contents: true } };
const passwordInput = (ui: ReactTestRenderer) => ui.root.findByType('input');
const openForm = (ui: ReactTestRenderer) => act(() => ui.root.findAll(node => node.type === 'button' && node.children.join('').startsWith('Unlock with owner password'))[0].props.onClick());
const type = (ui: ReactTestRenderer, value: string) => act(() => passwordInput(ui).props.onChange({ target: { value } }));
const submit = async (ui: ReactTestRenderer) => { await act(async () => { ui.root.findByType('form').props.onSubmit({ preventDefault() {} }); }); };
it('offers the owner-password unlock only for protected or unknown security, as a native button', async () => {
  vi.mocked(documentProperties).mockReset();
  vi.mocked(documentProperties).mockResolvedValueOnce(unlocked).mockResolvedValueOnce(locked).mockResolvedValueOnce(info);
  for (const [expected, id] of [[false, 11], [true, 12], [true, 13]] as const) {
    let ui!: ReactTestRenderer;
    await act(async () => { ui = create(<DocumentProperties document={{ ...document, id }} close={vi.fn()} />); });
    const buttons = ui.root.findAll(node => node.type === 'button' && node.children.join('').startsWith('Unlock with owner password'));
    expect(buttons).toHaveLength(expected ? 1 : 0);
    if (expected) expect(buttons[0].props.type).toBe('button');
    act(() => ui.unmount());
  }
});
it('checks the owner password once, clears it at once, never renders it and refreshes the security section on success', async () => {
  vi.mocked(documentProperties).mockReset(); vi.mocked(ownerUnlockDocument).mockReset();
  vi.mocked(documentProperties).mockResolvedValueOnce(locked).mockResolvedValueOnce(unlocked);
  vi.mocked(ownerUnlockDocument).mockRejectedValueOnce('Incorrect owner password. Nothing was changed.').mockResolvedValueOnce();
  let ui!: ReactTestRenderer;
  await act(async () => { ui = create(<DocumentProperties document={document} close={vi.fn()} />); });
  openForm(ui);
  const field = passwordInput(ui);
  expect(field.props.type).toBe('password'); expect(field.props.autoComplete).toBe('off'); expect(field.props.maxLength).toBe(1024); expect(field.props.autoFocus).toBe(true);
  expect(ui.root.findAllByType('form')).toHaveLength(1);
  const submitButton = () => ui.root.findAll(node => node.type === 'button' && node.props.type === 'submit')[0];
  expect(submitButton().props.disabled).toBe(true);
  type(ui, 'wrong secret');
  expect(submitButton().props.disabled).toBe(false);
  await submit(ui);
  expect(ownerUnlockDocument).toHaveBeenLastCalledWith(1, 4, 'wrong secret');
  expect(passwordInput(ui).props.value).toBe('');
  expect(ui.root.findByProps({ role: 'alert' }).children).toEqual(['Incorrect owner password. Nothing was changed.']);
  expect(documentProperties).toHaveBeenCalledTimes(1);
  expect(JSON.stringify(ui.toJSON())).not.toContain('wrong secret');
  type(ui, 'right secret');
  expect(ui.root.findAllByProps({ role: 'alert' })).toHaveLength(0);
  await submit(ui);
  expect(ownerUnlockDocument).toHaveBeenLastCalledWith(1, 4, 'right secret');
  expect(ownerUnlockDocument).toHaveBeenCalledTimes(2);
  expect(documentProperties).toHaveBeenCalledTimes(2);
  const text = JSON.stringify(ui.toJSON());
  expect(text).toContain('Security removed for this session'); expect(text).not.toContain('right secret');
  expect(ui.root.findAllByType('form')).toHaveLength(0);
  expect(ui.root.findAll(node => node.type === 'button' && node.children.join('').startsWith('Unlock with owner password'))).toHaveLength(0);
  act(() => ui.unmount());
});
it('limits the owner password to 1 KiB of UTF-8, ignores a second submit while checking and cancel discards the entry', async () => {
  vi.mocked(documentProperties).mockReset(); vi.mocked(ownerUnlockDocument).mockReset();
  vi.mocked(documentProperties).mockResolvedValue(locked);
  let resolve!: () => void;
  vi.mocked(ownerUnlockDocument).mockImplementation(() => new Promise<void>(done => { resolve = done; }));
  let ui!: ReactTestRenderer;
  await act(async () => { ui = create(<DocumentProperties document={document} close={vi.fn()} />); });
  openForm(ui);
  type(ui, 'é'.repeat(512));
  expect(passwordInput(ui).props.value).toHaveLength(512);
  type(ui, 'é'.repeat(513));
  expect(passwordInput(ui).props.value).toHaveLength(512);
  expect(JSON.stringify(ui.toJSON())).toContain('1 KiB');
  act(() => { ui.root.findByType('form').props.onSubmit({ preventDefault() {} }); ui.root.findByType('form').props.onSubmit({ preventDefault() {} }); });
  expect(ownerUnlockDocument).toHaveBeenCalledTimes(1);
  await act(async () => { resolve(); });
  openForm(ui);
  type(ui, 'abandoned');
  act(() => ui.root.findAll(node => node.type === 'button' && node.children.join('') === 'Cancel')[0].props.onClick());
  expect(ui.root.findAllByType('form')).toHaveLength(0);
  openForm(ui);
  expect(passwordInput(ui).props.value).toBe('');
  act(() => ui.unmount());
});
